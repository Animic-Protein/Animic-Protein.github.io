let current='ca';
export function t(key){ return messages[current]?.[key] ?? messages.ca[key] ?? key; }
export function language(){ return current; }
export function setLanguage(lang){
  current=messages[lang]?lang:'ca';
  const root=document.documentElement;
  root.lang=current==='yue'?'yue-Hant-HK':current;
  document.body.lang=root.lang;
  const select=document.querySelector('#languageSelect');
  if(select && select.value!==current) select.value=current;
  document.querySelectorAll('[data-i18n]').forEach(node=>{ const value=t(node.dataset.i18n); if(value) node.textContent=value; });
  document.querySelectorAll('[data-i18n-aria]').forEach(node=>{ const value=t(node.dataset.i18nAria); if(value) node.setAttribute('aria-label',value); });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(node=>{ const value=t(node.dataset.i18nPlaceholder); if(value) node.setAttribute('placeholder',value); });
  for(const field of Object.keys(defaultValues)){
    const node=document.getElementById(field);
    if(!node) continue;
    const oldValues=Object.values(defaultValues[field]);
    if(oldValues.includes(node.value)) node.value=defaultValues[field][current];
  }
  document.title=current==='ca'?'DISSENSUS · Prova de llibertat crítica · Còdex Viu':
    current==='ru'?'DISSENSUS · Проверка критической свободы · Живой Кодекс':
    current==='ko'?'DISSENSUS · 비판적 자유 시험 · 살아 있는 코덱스':'DISSENSUS · 批判自由測試 · 活典';
  const description=current==='ca'?'DISSENSUS: prova manual, reversible i sense puntuació del dret a rebutjar una proposta del Còdex Viu.':
    current==='ru'?'DISSENSUS: ручная обратимая проверка права отклонить предложение Живого Кодекса без оценки участника.':
    current==='ko'?'DISSENSUS: 살아 있는 코덱스의 제안을 거부할 권리를 점수 없이 수동으로 살펴보는 되돌릴 수 있는 시험입니다.':
    'DISSENSUS：以可逆的手動方式檢視拒絕活典建議的權利，不作評分。';
  document.querySelector('meta[name="description"]')?.setAttribute('content',description);
}
